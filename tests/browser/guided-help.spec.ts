import { test, expect } from "@playwright/test";
import { operatorSession } from "./helpers";

test("new and returning visitors can navigate, dismiss and replay tutorials", async ({ page }) => {
  await page.goto("/");
  await expect(page.getByLabel("Guided tour invitation")).toBeVisible();
  await page.getByRole("button", { name: "Take a tour" }).click();
  const dialog = page.getByRole("dialog", { name: "Our Jam guided tutorial" });
  await expect(dialog).toContainText("Join the jam");
  await expect(page.locator(".guided-help-spotlight")).toBeVisible();
  await dialog.getByRole("button", { name: "Next" }).click();
  await expect(dialog).toContainText("Help shape the music");
  await dialog.getByRole("button", { name: "Back" }).click();
  await expect(dialog).toContainText("Join the jam");
  await page.keyboard.press("Escape");
  await expect(dialog).toHaveCount(0);
  await expect(page.getByRole("button", { name: "Replay tour" })).toBeFocused();
  await page.reload();
  await page.getByRole("button", { name: "Replay tour" }).click();
  await dialog.getByRole("button", { name: "Next" }).click();
  await dialog.getByRole("button", { name: "Next" }).click();
  await dialog.getByRole("button", { name: "Finish" }).click();
  await expect(dialog).toHaveCount(0);
});
test("the fan tutorial points to real voting and released-track controls", async ({ page }) => {
  const events = await (await page.request.get("/api/events")).json();
  const slug = events.events.find((event: any) => event.title === "The first wave").slug;
  await page.goto("/event/" + slug);
  await expect(page.locator(".audience .vote-panel")).toBeVisible();
  await page.getByRole("button", { name: "Take a tour" }).click();
  const dialog = page.getByRole("dialog", { name: "Our Jam guided tutorial" });
  await expect(dialog).toContainText("The music playing now");
  await dialog.getByRole("button", { name: "Next" }).click();
  await expect(dialog).toContainText("Explore the room");
  await dialog.getByRole("button", { name: "Next" }).click();
  await expect(dialog).toContainText("Your five points");
  await dialog.getByRole("button", { name: "Skip tutorial" }).click();
  await page.getByRole("button", { name: "I'm in. Let's make music" }).click();
  await expect(page.getByLabel("What would you mix this with?")).toBeVisible();
  await page.getByRole("button", { name: "Replay tour" }).click();
  await expect(dialog).toBeVisible();
  await dialog.getByRole("button", { name: "Skip tutorial" }).click();
});
test("the performer gets separate access and console tours", async ({ page }) => {
  await page.goto("/performer");
  await page.getByRole("button", { name: "Take a tour" }).click();
  const dialog = page.getByRole("dialog", { name: "Our Jam guided tutorial" });
  await expect(dialog).toContainText("Private performer access");
  await dialog.getByRole("button", { name: "Finish" }).click();
  await operatorSession(page);
  const events = await (await page.request.get("/api/events")).json();
  const slug = events.events.find((event: any) => event.title === "The first wave").slug;
  await page.goto("/performer/" + slug);
  await expect(page.locator(".console .show-player")).toBeVisible();
  await page.getByRole("button", { name: "Take a tour" }).click();
  await expect(dialog).toContainText("Your live show");
  await dialog.getByRole("button", { name: "Next" }).click();
  await expect(dialog).toContainText("Control real playback");
  await dialog.getByRole("button", { name: "Skip tutorial" }).click();
});
